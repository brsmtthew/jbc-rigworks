test('simultaneous checkouts cannot oversell the last stock unit', async ({ page, context }) => {
  await setup(page)
  await page.evaluate(() => {
    const key = 'jbc-rigworks:workspace:v1:admin@example.com'
    const data = JSON.parse(localStorage.getItem(key)!)
    data.inventory[0].stock = 1
    localStorage.setItem(key, JSON.stringify(data)); window.dispatchEvent(new Event('jbc-workspace-change'))
  })
  const second = await context.newPage()
  await second.goto('/login')
  await second.evaluate(() => sessionStorage.setItem('jbc-rigworks:session', JSON.stringify({ id: 'admin@example.com', email: 'admin@example.com', name: 'Admin', role: 'admin' })))
  await second.goto('/pos')
  for (const tab of [page, second]) {
    await tab.getByRole('button', { name: 'Add Processor test part', exact: true }).click()
    await tab.getByRole('button', { name: 'Review checkout' }).click()
    await tab.getByLabel('Customer name', { exact: true }).fill('Last unit buyer')
  }
  await Promise.all([page.getByRole('button', { name: 'Complete sale' }).click(), second.getByRole('button', { name: 'Complete sale' }).click()])
  await expect.poll(async () => page.evaluate(() => JSON.parse(localStorage.getItem('jbc-rigworks:workspace:v1:admin@example.com')!).sales.length)).toBe(1)
  const data = await page.evaluate(() => JSON.parse(localStorage.getItem('jbc-rigworks:workspace:v1:admin@example.com')!))
  expect(data.inventory[0].stock).toBe(0)
  await expect.poll(async () => (await page.getByRole('alert').count()) + (await second.getByRole('alert').count())).toBe(1)
  await second.close()
})

