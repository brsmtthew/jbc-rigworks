test('new pages fit mobile screens, headings stick, and forms pass accessibility checks', async ({ page }) => {
  await setup(page)
  await page.emulateMedia({ reducedMotion: 'reduce' })
  for (const width of [320, 768, 1440]) {
    await page.setViewportSize({ width, height: 800 })
    for (const route of ['/pos', '/services', '/pc-building', '/pc-identifier', '/settings', '/reports']) {
      await page.goto(route)
      await expect(page.getByRole('heading', { level: 1 })).toBeVisible()
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth && Array.from(document.querySelectorAll('.page-content')).every(element => element.scrollWidth <= element.clientWidth))).toBe(true)
      await page.evaluate(() => document.querySelector('.page-content')!.scrollTo({ top: 700, behavior: 'instant' }))
      const header = await page.locator('.page-heading').boundingBox()
      expect(header!.y).toBeGreaterThanOrEqual(67)
      expect(header!.y).toBeLessThan(120)
    }
  }
  for (const route of ['/pos', '/services', '/pc-building', '/pc-identifier', '/settings']) {
    await page.goto(route)
    const audit = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()
    expect(audit.violations.map(item => ({ id: item.id, targets: item.nodes.map(node => node.target) }))).toEqual([])
  }
})
