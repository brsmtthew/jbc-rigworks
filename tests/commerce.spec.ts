test('exports are readable Excel files with numeric values and frozen headers', async ({ page }) => {
  await setup(page)
  await page.goto('/inventory')
  const pending = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export Excel' }).click()
  await expect(page.getByRole('dialog', { name: 'Excel preview' })).toBeVisible()
  await page.getByRole('button', { name: 'Download Excel' }).click()
  const download = await pending
  expect(download.suggestedFilename()).toBe('inventory.xlsx')
  const workbook = new ExcelJS.Workbook()
  await workbook.xlsx.readFile((await download.path())!)
  const sheet = workbook.getWorksheet('Records')!
  expect(sheet.getCell('A1').value).toBe('SKU')
  expect(sheet.getCell('D2').value).toBe(5)
  expect(sheet.getCell('F2').value).toBe(1000)
  expect(sheet.views[0]).toMatchObject({ state: 'frozen', ySplit: 1 })
})

