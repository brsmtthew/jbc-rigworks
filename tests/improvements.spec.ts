test('unset delivery rates require configuration and malformed records are not overwritten', async ({ page }) => {
  await setup(page)
  await page.evaluate(() => localStorage.setItem('jbc-rigworks:shop-settings:v1', '{}'))
  await page.reload()
  await page.getByRole('button', { name: 'Add Processor item', exact: true }).click()
  await delivery(page)
  await expect(page.getByRole('button', { name: 'Complete sale' })).toBeDisabled()
  await expect(page.getByRole('status')).toContainText('Delivery quote required')
  await page.evaluate(() => localStorage.setItem('jbc-rigworks:workspace:v1:admin@example.com', '{invalid'))
  await page.goto('/expenses')
  await expect(page.getByRole('alert')).toContainText('Saving is paused')
  await page.getByRole('button', { name: 'Record expense' }).click()
  await page.getByLabel('Description', { exact: true }).fill('Test')
  await page.getByLabel('Category', { exact: true }).fill('Test')
  await page.getByRole('button', { name: 'Save record' }).click()
  await expect(page.getByRole('dialog').getByRole('alert')).toContainText('Saving is paused')
  expect(await page.evaluate(() => localStorage.getItem('jbc-rigworks:workspace:v1:admin@example.com'))).toBe('{invalid')
})
