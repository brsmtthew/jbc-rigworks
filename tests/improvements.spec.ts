import { test, expect, type Page } from '@playwright/test'
const stock = ['Processor', 'Motherboard', 'Memory', 'Graphics', 'Storage', 'Power supply', 'Case', 'Cooling'].map((component, index) => ({ id: 'p' + index, name: component + ' item', sku: 'P' + index, category: component, component, tier: 'Mid', stock: 10, minimum: 1, price: 1000, cost: 400, ...(index === 0 ? { warrantyMonths: '6', warrantyTerms: 'CPU warranty terms.' } : {}) }))
const settings = { name: 'Test shop', prefix: 'INV', taxRate: 10, labor: 0, homeSurcharge: '150', transportBase: '30', transportPerKm: '10', warrantyMonths: '12', warrantyTerms: 'Workshop parts warranty.', cleaning: { Desktop: { Low: '500', Mid: '700', High: '900' }, Laptop: { Low: '600', Mid: '800', High: '1000' } } }
async function setup(page: Page, role = 'admin') {
  await page.goto('/login')
  await page.evaluate(({ stock, settings, role }) => {
    localStorage.clear(); sessionStorage.clear()
    localStorage.setItem('jbc-rigworks:workspace:v1:admin@example.com', JSON.stringify({ jobs: [], sales: [], expenses: [], inventory: stock, bundles: [] }))
    localStorage.setItem('jbc-rigworks:shop-owner:v1', 'admin@example.com')
    localStorage.setItem('jbc-rigworks:shop-settings:v1', JSON.stringify(settings))
    sessionStorage.setItem('jbc-rigworks:session', JSON.stringify({ id: role + '@example.com', email: role + '@example.com', name: role, role }))
  }, { stock, settings, role })
  await page.goto(role === 'admin' ? '/pos' : '/customer/shop')
}
async function delivery(page: Page) {
  await page.getByRole('button', { name: 'Review checkout' }).click()
  await page.getByRole('combobox', { name: 'Fulfillment', exact: true }).selectOption('Delivery')
  await page.getByLabel('Delivery address').fill('123 Test street')
  await page.getByLabel('One-way road distance (km)').fill('5')
  await page.getByLabel('Customer contact', { exact: true }).fill('09123456789')
}
test('selected item bundles guarantee free delivery and preserve item warranty snapshots', async ({ page }) => {
  await setup(page)
  await page.getByRole('button', { name: 'Bundles & PC sets', exact: true }).click()
  await page.getByRole('button', { name: 'Create an item bundle', exact: true }).click()
  await page.getByLabel('Bundle name').fill('Upgrade bundle')
  await page.getByLabel('Processor', { exact: true }).selectOption('p0')
  await page.getByLabel('Memory', { exact: true }).selectOption('p2')
  await page.getByLabel('Bundle quantity: Processor item', { exact: true }).fill('1')
  await page.getByLabel('Bundle quantity: Memory item', { exact: true }).fill('2')
  await page.getByRole('button', { name: 'Save bundle' }).click()
  await expect(page.getByRole('button', { name: 'Choose Upgrade bundle', exact: true })).toBeVisible()
  await page.evaluate(() => sessionStorage.setItem('jbc-rigworks:session', JSON.stringify({ id: 'customer@example.com', email: 'customer@example.com', name: 'Customer', role: 'customer' })))
  await page.goto('/customer/shop')
  await expect(page.getByText('Create an item bundle')).toHaveCount(0)
  await page.getByRole('button', { name: 'Bundles & PC sets', exact: true }).click()
  await page.getByRole('button', { name: 'Choose Upgrade bundle', exact: true }).click()
  await delivery(page)
  await expect(page.locator('.fulfillment-note')).toContainText('free delivery guaranteed')
  await expect(page.locator('.checkout-totals > div').filter({ has: page.getByText('Delivery', { exact: true }) })).toContainText('0.00')
  await page.getByRole('button', { name: 'Place local order' }).click()
  await expect(page.getByRole('dialog')).toContainText('Free delivery guaranteed: Upgrade bundle')
  await expect(page.getByRole('dialog')).toContainText('Warranty: 6 months')
  await expect(page.getByRole('dialog')).toContainText('Warranty: 12 months')
  const sale = await page.evaluate(() => JSON.parse(localStorage.getItem('jbc-rigworks:workspace:v1:admin@example.com')!).sales[0])
  expect(sale.charges.delivery).toBe(0)
  expect(sale.total).toBe(3300)
  expect(sale.lines[0].warranty).toMatchObject({ months: 6, terms: 'CPU warranty terms.' })
  expect(sale.lines[0].warranty.expires).toMatch(/^\d{4}-\d{2}-\d{2}$/)
  await page.evaluate(() => localStorage.setItem('jbc-rigworks:shop-settings:v1', JSON.stringify({ warrantyMonths: '1', warrantyTerms: 'Changed terms' })))
  await page.goto('/customer/records')
  await page.getByRole('button', { name: /^Invoice INV-/ }).click()
  await expect(page.getByRole('dialog')).toContainText('Warranty: 12 months')
  await expect(page.getByRole('dialog')).not.toContainText('Changed terms')
})
